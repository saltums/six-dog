-- SiX-DOG ARCHIVE 管理者機能(2026-11-14)
-- 投稿(動画・関連URL・告知ポスト・公演情報の修正・反応)を、管理者パスワードを知っている人だけが削除できるようにする。
-- パスワードはサーバー側(この関数の中)でだけ確かめる。ハッシュ(bcrypt)だけを保存し、平文はどこにも残さない。
-- 保存用のテーブルは RLS を有効にしてポリシーを作らないので、公開キー(anon)からは読めない。

create table if not exists public.sixdog_admin (
  id int primary key default 1 check (id = 1),
  pass_hash text not null,
  updated_at timestamptz not null default now()
);
alter table public.sixdog_admin enable row level security;
revoke all on public.sixdog_admin from anon, authenticated;

create table if not exists public.sixdog_admin_attempts (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  ok boolean not null
);
alter table public.sixdog_admin_attempts enable row level security;
revoke all on public.sixdog_admin_attempts from anon, authenticated;

-- 内部用:パスワードを確かめて 'ok' / 'wrong' / 'locked' / 'not_set' を返す。
-- 例外を投げると失敗の記録まで取り消されてしまうので、結果は値で返す。10分間に10回間違えると受け付けない
create or replace function public.sixdog_admin_verify(p_pass text)
returns text language plpgsql security definer set search_path = public, extensions as $$
declare h text; fails int;
begin
  select count(*) into fails from sixdog_admin_attempts where not ok and at > now() - interval '10 minutes';
  if fails >= 10 then return 'locked'; end if;
  select pass_hash into h from sixdog_admin where id = 1;
  if h is null then return 'not_set'; end if;
  if p_pass is null or crypt(p_pass, h) <> h then
    insert into sixdog_admin_attempts(ok) values (false);
    return 'wrong';
  end if;
  delete from sixdog_admin_attempts where at < now() - interval '1 day';
  return 'ok';
end $$;
revoke all on function public.sixdog_admin_verify(text) from public, anon, authenticated;

-- パスワードが設定済みかどうか
create or replace function public.sixdog_admin_status()
returns boolean language sql security definer set search_path = public as $$
  select exists(select 1 from sixdog_admin where id = 1);
$$;

-- 最初の1回だけ:パスワードを設定する。'ok' / 'already_set' / 'too_short'
create or replace function public.sixdog_admin_setup(p_new text)
returns text language plpgsql security definer set search_path = public, extensions as $$
begin
  if exists(select 1 from sixdog_admin where id = 1) then return 'already_set'; end if;
  if p_new is null or length(p_new) < 8 then return 'too_short'; end if;
  insert into sixdog_admin(id, pass_hash) values (1, crypt(p_new, gen_salt('bf', 10)));
  return 'ok';
end $$;

-- パスワードを変える(今のパスワードが必要)
create or replace function public.sixdog_admin_change(p_pass text, p_new text)
returns text language plpgsql security definer set search_path = public, extensions as $$
declare v text;
begin
  v := sixdog_admin_verify(p_pass);
  if v <> 'ok' then return v; end if;
  if p_new is null or length(p_new) < 8 then return 'too_short'; end if;
  update sixdog_admin set pass_hash = crypt(p_new, gen_salt('bf', 10)), updated_at = now() where id = 1;
  return 'ok';
end $$;

-- ログインの確認だけ
create or replace function public.sixdog_admin_login(p_pass text)
returns text language plpgsql security definer set search_path = public, extensions as $$
begin
  return sixdog_admin_verify(p_pass);
end $$;

-- 削除。p_kind: video / link / tweet / hype / emoi は id で、override は日付(YYYY-MM-DD)で消す。
-- 成功なら 'ok:件数'、だめなら verify の結果か 'unknown_kind'
create or replace function public.sixdog_admin_delete(p_pass text, p_kind text, p_key text)
returns text language plpgsql security definer set search_path = public, extensions as $$
declare v text; n int;
begin
  v := sixdog_admin_verify(p_pass);
  if v <> 'ok' then return v; end if;
  if p_kind = 'video' then delete from sixdog_videos where id = p_key::bigint;
  elsif p_kind = 'link' then delete from sixdog_event_links where id = p_key::bigint;
  elsif p_kind = 'tweet' then delete from sixdog_event_tweets where id = p_key::bigint;
  elsif p_kind = 'hype' then delete from sixdog_event_hype where id = p_key::bigint;
  elsif p_kind = 'emoi' then delete from sixdog_event_emoi where id = p_key::bigint;
  elsif p_kind = 'override' then delete from sixdog_event_overrides where event_date = p_key::date;
  else return 'unknown_kind';
  end if;
  get diagnostics n = row_count;
  return 'ok:' || n;
end $$;

grant execute on function public.sixdog_admin_status() to anon, authenticated;
grant execute on function public.sixdog_admin_setup(text) to anon, authenticated;
grant execute on function public.sixdog_admin_change(text, text) to anon, authenticated;
grant execute on function public.sixdog_admin_login(text) to anon, authenticated;
grant execute on function public.sixdog_admin_delete(text, text, text) to anon, authenticated;
