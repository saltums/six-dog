-- =====================================================================
-- SiX-DOG ARCHIVE の Supabase テーブル定義と権限(Row Level Security)
--
-- 新しい Supabase プロジェクトに SiX-DOG のDBを作り直すときは:
--   1. このファイルを SQL Editor で丸ごと実行する
--   2. scripts/Import-Supabase.ps1 で data/supabase/*.json を流し込む
--   3. 末尾の「連番の再同期」ブロックを実行する
--   4. docs/supabase-config.js の url / anonKey / tablePrefix を新しい値にする
--
-- 他アプリと同居するプロジェクト(現在は various_apps)に置くため、
-- テーブル名に sixdog_ の接頭辞を付けている。接頭辞を変えるときは
-- このファイル中の "sixdog_" を一括置換し、supabase-config.js も合わせる。
--
-- 権限の方針: サイトはログイン不要で誰でも閲覧・投稿できる(anon key は公開鍵)。
-- 削除・更新を許すかはテーブルごとに意図して決めている(下記コメント参照)。
-- =====================================================================

-- 公演情報の手動追加・修正(Wayback由来の元データ events.json を日付単位で上書きする)
create table if not exists public.sixdog_event_overrides (
  event_date  date primary key,
  title       text,
  open_time   text,
  start_time  text,
  price_adv   integer,
  price_door  integer,
  price_note  text,
  performers  jsonb,
  notes       text,
  updated_at  timestamptz not null default now()
);

-- 公演に紐づく関連ページ(告知ツイート・ブログ・アーカイブ等の出典URL)
create table if not exists public.sixdog_event_links (
  id            bigint generated by default as identity primary key,
  event_date    date not null,
  url           text not null,
  title         text,
  submitted_by  text,
  submitted_at  timestamptz not null default now(),
  unique (event_date, url)
);

-- 公演当日のX(旧Twitter)投稿の埋め込み
create table if not exists public.sixdog_event_tweets (
  id            bigint generated by default as identity primary key,
  event_date    date not null,
  tweet_id      text not null,
  submitted_by  text,
  submitted_at  timestamptz not null default now(),
  unique (event_date, tweet_id)
);

-- 企画シリーズ名の表記ゆれをまとめるマッピング(BIダッシュボード用)
create table if not exists public.sixdog_event_title_groups (
  id             bigint generated by default as identity primary key,
  variant_title  text not null unique,
  group_name     text not null,
  submitted_by   text,
  submitted_at   timestamptz not null default now()
);

-- 出演者ごとの動画URL
create table if not exists public.sixdog_videos (
  id              bigint generated by default as identity primary key,
  event_date      date not null,
  performer_name  text not null,
  video_url       text not null check (video_url ~* '^https?://'),
  video_title     text,
  submitted_by    text,
  submitted_at    timestamptz not null default now(),
  notes           text
);

-- 「アツかった」「エモい」の反応(1タップ1行)
create table if not exists public.sixdog_event_hype (
  id          bigint generated by default as identity primary key,
  event_date  date not null,
  created_at  timestamptz not null default now()
);
create table if not exists public.sixdog_event_emoi (
  id          bigint generated by default as identity primary key,
  event_date  date not null,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------
alter table public.sixdog_event_overrides    enable row level security;
alter table public.sixdog_event_links        enable row level security;
alter table public.sixdog_event_tweets       enable row level security;
alter table public.sixdog_event_title_groups enable row level security;
alter table public.sixdog_videos             enable row level security;
alter table public.sixdog_event_hype         enable row level security;
alter table public.sixdog_event_emoi         enable row level security;

-- 公演情報: 閲覧・追加・修正は誰でも可。削除は不可(荒らしで消されないように)
create policy "sixdog overrides select" on public.sixdog_event_overrides for select using (true);
create policy "sixdog overrides insert" on public.sixdog_event_overrides for insert with check (true);
create policy "sixdog overrides update" on public.sixdog_event_overrides for update using (true) with check (true);

-- 関連URL・当日ツイート: 閲覧・追加・解除(削除)は誰でも可
create policy "sixdog links select" on public.sixdog_event_links for select using (true);
create policy "sixdog links insert" on public.sixdog_event_links for insert with check (true);
create policy "sixdog links delete" on public.sixdog_event_links for delete using (true);
create policy "sixdog tweets select" on public.sixdog_event_tweets for select using (true);
create policy "sixdog tweets insert" on public.sixdog_event_tweets for insert with check (true);
create policy "sixdog tweets delete" on public.sixdog_event_tweets for delete using (true);

-- シリーズ名グループ: すべて誰でも可
create policy "sixdog groups select" on public.sixdog_event_title_groups for select using (true);
create policy "sixdog groups insert" on public.sixdog_event_title_groups for insert with check (true);
create policy "sixdog groups update" on public.sixdog_event_title_groups for update using (true) with check (true);
create policy "sixdog groups delete" on public.sixdog_event_title_groups for delete using (true);

-- 動画: 閲覧・投稿・編集・解除は誰でも可(2026-08-08 に編集・解除を意図して解禁)
create policy "sixdog videos select" on public.sixdog_videos for select using (true);
create policy "sixdog videos insert" on public.sixdog_videos for insert with check (true);
create policy "sixdog videos update" on public.sixdog_videos for update using (true) with check (true);
create policy "sixdog videos delete" on public.sixdog_videos for delete using (true);

-- 反応: 閲覧・追加のみ(取り消しは荒らし対策のため不可にしている)
create policy "sixdog hype select" on public.sixdog_event_hype for select using (true);
create policy "sixdog hype insert" on public.sixdog_event_hype for insert with check (true);
create policy "sixdog emoi select" on public.sixdog_event_emoi for select using (true);
create policy "sixdog emoi insert" on public.sixdog_event_emoi for insert with check (true);

